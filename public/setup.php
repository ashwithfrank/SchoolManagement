<?php
/**
 * First-run setup. Step 1: connect to MySQL, create the tables, write app/config/config.php.
 * Step 2: school name, first academic year and the first Administrator.
 * Only reachable from the server computer itself (localhost) and only until the first admin exists.
 */
require dirname(__DIR__) . '/app/bootstrap.php';

use App\Core\{Config, Csrf, Dates, Db, Flash, Migrator, Settings, UserError, View};
use App\Services\UserService;

$remote = $_SERVER['REMOTE_ADDR'] ?? '';
if (!in_array($remote, ['127.0.0.1', '::1'], true)) {
    http_response_code(403);
    exit('<!doctype html><meta charset="utf-8"><body style="font-family:Segoe UI,Arial;max-width:600px;margin:12vh auto"><h2>Setup is only available on the server computer</h2><p>Open this page on the PC that runs XAMPP, using <b>http://localhost/...</b>. This protects a new installation from being claimed by someone else on the network.</p></body>');
}

$stepTwo = Config::exists();
if ($stepTwo) {
    try {
        if ((int) Db::pdo()->query('SELECT COUNT(*) FROM users')->fetchColumn() > 0) {
            Flash::info('Setup is already complete. Please sign in.');
            redirect(base_path() . '/login.php');
        }
    } catch (Throwable $e) {
        http_response_code(503);
        exit(View::partial('auth/db_error', ['debug' => true, 'error' => $e->getMessage()]));
    }
}

$checks = [
    'PHP 8.0 or newer'           => PHP_VERSION_ID >= 80000,
    'pdo_mysql extension'        => extension_loaded('pdo_mysql'),
    'mbstring extension'         => extension_loaded('mbstring'),
    'fileinfo extension'         => extension_loaded('fileinfo'),
    'openssl (encrypted backups)' => function_exists('openssl_encrypt'),
    'zip (backups)'              => class_exists('ZipArchive'),
    'gd (photo processing; optional)' => extension_loaded('gd'),
    'app/config writable'        => is_writable(APP_DIR . '/config'),
    'storage folders writable'   => is_writable(STORAGE_DIR) && is_writable(STORAGE_DIR . '/student_photos') && is_writable(STORAGE_DIR . '/logs'),
];
$required = array_diff_key($checks, ['gd (photo processing; optional)' => 1]);
$ready = !in_array(false, $required, true);

$error = null;
$in = $_POST;
if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    Csrf::enforce();
    try {
        if (!$ready) {
            throw new UserError('Fix the red items in the checklist first, then reload this page.');
        }
        if (!$stepTwo) {
            // ---- step 1: database ----
            $db = [
                'host' => trim((string) ($in['host'] ?? '127.0.0.1')) ?: '127.0.0.1',
                'port' => (int) ($in['port'] ?? 3306) ?: 3306,
                'name' => trim((string) ($in['name'] ?? '')),
                'user' => trim((string) ($in['user'] ?? '')),
                'pass' => (string) ($in['pass'] ?? ''),
                'charset' => 'utf8mb4',
            ];
            if (!preg_match('/^[A-Za-z0-9_]{1,60}$/', $db['name'])) {
                throw new UserError('Database name may contain letters, numbers and underscores only.');
            }
            if ($db['user'] === '') {
                throw new UserError('Enter the database user (XAMPP default: root).');
            }
            try {
                if (!empty($in['create_db'])) {
                    $srv = Db::connect($db, false);
                    $srv->exec('CREATE DATABASE IF NOT EXISTS `' . $db['name'] . '` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci');
                }
                $pdo = Db::connect($db, true);
            } catch (PDOException $e) {
                throw new UserError('Could not connect: ' . $e->getMessage());
            }
            if (strtolower($db['user']) === 'root' && $db['pass'] === '' && !empty($in['accept_root'])) {
                Flash::warning('You are using the MySQL root user without a password. That is acceptable for a single offline PC, but create a dedicated user before sharing the system on a LAN.');
            } elseif (strtolower($db['user']) === 'root' && $db['pass'] === '') {
                throw new UserError('You are connecting as root with no password. Tick the box to confirm this is a single local PC, or create a dedicated MySQL user (see README).');
            }
            Migrator::run($pdo);
            Migrator::seed($pdo);
            $cfg = [
                'db' => $db,
                'app' => ['timezone' => 'Asia/Kolkata', 'debug' => false, 'session_name' => 'AOSMSSESS', 'idle_minutes' => 30, 'max_session_hrs' => 12],
            ];
            $php = "<?php\n// Generated by setup.php on " . date('c') . ". Contains the database password: keep private.\nreturn " . var_export($cfg, true) . ";\n";
            if (file_put_contents(Config::path(), $php, LOCK_EX) === false) {
                throw new UserError('The database was prepared but app/config/config.php could not be written. Make app/config writable and run setup again with a new, empty database.');
            }
            @chmod(Config::path(), 0640);
            Flash::success('Database ready. Now create the administrator account.');
            redirect(base_path() . '/setup.php');
        }
        // ---- step 2: school, year, admin ----
        $school = trim((string) ($in['school_name'] ?? ''));
        $yName = trim((string) ($in['year_name'] ?? ''));
        $yStart = (string) ($in['year_start'] ?? '');
        $yEnd = (string) ($in['year_end'] ?? '');
        if ($school === '' || mb_strlen($school) > 120) {
            throw new UserError('Enter the school name.');
        }
        if ($yName === '' || !Dates::isValid($yStart) || !Dates::isValid($yEnd) || $yEnd <= $yStart) {
            throw new UserError('Enter the academic year name (e.g. 2026-27) with valid start and end dates.');
        }
        if ((string) ($in['password'] ?? '') !== (string) ($in['password2'] ?? '')) {
            throw new UserError('The two passwords do not match.');
        }
        Db::tx(function () use ($school, $yName, $yStart, $yEnd, $in) {
            UserService::createFirstAdmin(trim((string) ($in['username'] ?? '')), (string) ($in['full_name'] ?? ''), (string) ($in['password'] ?? ''));
            Settings::set('school_name', $school);
            Db::exec('INSERT INTO academic_years (name, start_date, end_date, active_flag, created_at) VALUES (?, ?, ?, 1, NOW())', [$yName, $yStart, $yEnd]);
        });
        Flash::success('Setup complete. Sign in with the administrator account you just created.');
        redirect(base_path() . '/login.php');
    } catch (UserError $e) {
        $error = $e->getMessage();
    }
}
$y = (int) date('n') >= 4 ? (int) date('Y') : (int) date('Y') - 1;
echo View::partial('auth/setup', [
    'stepTwo' => $stepTwo, 'checks' => $checks, 'ready' => $ready, 'error' => $error, 'in' => $in, 'flashes' => \App\Core\Flash::pull(),
    'defaultYear' => ['name' => $y . '-' . substr((string) ($y + 1), 2), 'start' => "$y-04-01", 'end' => ($y + 1) . '-03-31'],
]);
